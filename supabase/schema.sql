-- ── Bajet database (Supabase / Postgres) ─────────────────────────────────────
-- Applied to the "Bajet" Supabase project (ref ycjbdfdxuqcfyhiwcadn) as the
-- migration `bajet_schema`. Kept here as the source of truth; to recreate the
-- database elsewhere, run this file once in the SQL editor.
--
-- The browser talks to Supabase directly (like the Perut repo). Security model:
--   * Signed-in users can READ only their own cycles and periods (RLS).
--   * All writes go through the functions at the bottom, which validate input,
--     enforce the business rules and run in one transaction. The only direct
--     write allowed is deleting your own cycle (periods cascade).
--   * Rows copied from the old Go/Neon backend keep the old Google account id
--     in legacy_user_id until their owner signs in and claim_legacy_cycles()
--     attaches them to the Supabase user.

-- ── Tables ───────────────────────────────────────────────────────────────────

create table public.cycles (
  id             bigint generated by default as identity primary key,
  -- Owner. Null only for rows migrated from the old backend that their owner
  -- hasn't claimed yet (see claim_legacy_cycles).
  user_id        uuid references auth.users (id) on delete cascade,
  -- Google account id ("sub") from the old Go/Neon backend, kept for claiming.
  legacy_user_id text,
  start_date     date not null,
  end_date       date not null,
  total_budget   numeric(14, 2) not null check (total_budget > 0),
  division_mode  text not null default 'equal'
                 check (division_mode in ('equal', 'behavioral', 'menurun', 'progresif')),
  num_periods    int not null check (num_periods between 1 and 12),
  created_at     timestamptz not null default now(),
  constraint cycles_dates check (end_date > start_date),
  constraint cycles_owner check (user_id is not null or legacy_user_id is not null)
);
create index cycles_user_idx on public.cycles (user_id, created_at desc);
create index cycles_legacy_idx on public.cycles (legacy_user_id) where user_id is null;

create table public.periods (
  id            bigint generated by default as identity primary key,
  cycle_id      bigint not null references public.cycles (id) on delete cascade,
  period_number int not null check (period_number between 1 and 12),
  start_date    date not null,
  end_date      date not null,
  budget        numeric(14, 2) not null,
  status        text not null default 'open' check (status in ('open', 'completed')),
  result_type   text not null default '' check (result_type in ('', 'sisa', 'defisit')),
  result_amount numeric(14, 2) not null default 0 check (result_amount >= 0),
  created_at    timestamptz not null default now(),
  constraint periods_dates check (end_date >= start_date),
  constraint periods_number_unique unique (cycle_id, period_number)
);

create table public.waitlist (
  id         bigint generated by default as identity primary key,
  email      text not null unique check (position('@' in email) > 1),
  source     text not null default 'landing',
  ip         text not null default '',
  created_at timestamptz not null default now()
);

-- ── Row Level Security ───────────────────────────────────────────────────────
-- Browsers may read only their own data. Every write goes through the
-- functions below (security definer), except deleting your own cycle.

alter table public.cycles   enable row level security;
alter table public.periods  enable row level security;
alter table public.waitlist enable row level security;

revoke all on public.cycles, public.periods, public.waitlist from anon, authenticated;
grant select, delete on public.cycles to authenticated;
grant select on public.periods to authenticated;
grant insert on public.waitlist to anon, authenticated;

create policy "read own cycles" on public.cycles
  for select to authenticated using (user_id = (select auth.uid()));
create policy "delete own cycles" on public.cycles
  for delete to authenticated using (user_id = (select auth.uid()));
create policy "read own periods" on public.periods
  for select to authenticated using (exists (
    select 1 from public.cycles c where c.id = cycle_id and c.user_id = (select auth.uid())
  ));
create policy "anyone can join the waitlist" on public.waitlist
  for insert to anon, authenticated with check (true);

-- ── Period math (mirrors frontend/src/lib/utils.js) ──────────────────────────

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

-- Budget per period; the last period takes the rounding remainder so the sum is exact.
create function private.calc_budgets(total numeric, n int, mode text)
returns numeric[] language plpgsql immutable set search_path = '' as $$
declare
  tw numeric := case when mode in ('progresif', 'menurun') then n * (n + 1) / 2 else n end;
  w numeric;
  out numeric[] := '{}';
  s numeric := 0;
begin
  for i in 0 .. n - 2 loop
    w := case mode when 'progresif' then i + 1 when 'menurun' then n - i else 1 end;
    out := out || floor(total * w / tw);
    s := s + floor(total * w / tw);
  end loop;
  return out || (total - s);
end $$;

-- Splits total_days into n periods; extra days go to the front. Behavioral moves
-- one more day to P1 without ever leaving a period empty. Requires total_days >= n.
create function private.calc_distribution(total_days int, n int, mode text)
returns int[] language plpgsql immutable set search_path = '' as $$
declare
  base int := total_days / n;
  extra int := total_days % n;
  dist int[] := array_fill(base, array[n]);
  donor int;
begin
  for i in 1 .. extra loop dist[i] := dist[i] + 1; end loop;
  if mode = 'behavioral' and n > 1 then
    donor := case when extra >= 2 then extra else n end;  -- 1-based
    if dist[donor] > 1 then
      dist[1] := dist[1] + 1;
      dist[donor] := dist[donor] - 1;
    end if;
  end if;
  return dist;
end $$;

create function private.validate_cycle(p_start date, p_end date, p_total numeric, p_mode text, p_n int)
returns void language plpgsql immutable set search_path = '' as $$
begin
  if p_start is null or p_end is null then raise exception 'invalid dates'; end if;
  if p_end <= p_start then raise exception 'end_date must be after start_date'; end if;
  if p_total is null or p_total <= 0 then raise exception 'total_budget must be greater than 0'; end if;
  if p_mode not in ('equal', 'behavioral', 'menurun', 'progresif') then raise exception 'invalid division_mode'; end if;
  if p_n is null or p_n < 1 or p_n > 12 then raise exception 'num_periods must be between 1 and 12'; end if;
  if (p_end - p_start + 1) < p_n then raise exception 'date range is shorter than the number of periods'; end if;
end $$;

create function private.build_periods(p_cycle bigint)
returns void language plpgsql set search_path = '' as $$
declare
  c public.cycles;
  dist int[];
  budgets numeric[];
  cur date;
begin
  select * into c from public.cycles where id = p_cycle;
  dist := private.calc_distribution(c.end_date - c.start_date + 1, c.num_periods, c.division_mode);
  budgets := private.calc_budgets(c.total_budget, c.num_periods, c.division_mode);
  cur := c.start_date;
  for i in 1 .. c.num_periods loop
    insert into public.periods (cycle_id, period_number, start_date, end_date, budget)
    values (c.id, i, cur, cur + dist[i] - 1, budgets[i]);
    cur := cur + dist[i];
  end loop;
end $$;

-- Cycle as the app expects it: the cycle fields plus its periods in order.
create function private.cycle_json(p_cycle bigint)
returns jsonb language sql stable set search_path = '' as $$
  select (to_jsonb(c) - 'user_id' - 'legacy_user_id') || jsonb_build_object('periods',
    coalesce((select jsonb_agg(to_jsonb(p) order by p.period_number) from public.periods p where p.cycle_id = c.id), '[]'::jsonb))
  from public.cycles c where c.id = p_cycle
$$;

create function private.require_user() returns uuid
language plpgsql stable set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'not signed in' using errcode = '28000'; end if;
  return auth.uid();
end $$;

-- ── API (called from the browser via supabase.rpc) ───────────────────────────

create function public.create_cycle(p_start date, p_end date, p_total numeric, p_mode text default 'equal', p_n int default 4)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := private.require_user();
  new_id bigint;
begin
  perform private.validate_cycle(p_start, p_end, p_total, p_mode, p_n);
  insert into public.cycles (user_id, start_date, end_date, total_budget, division_mode, num_periods)
  values (uid, p_start, p_end, p_total, p_mode, p_n) returning id into new_id;
  perform private.build_periods(new_id);
  return private.cycle_json(new_id);
end $$;

-- Budget and mode can always change (check-ins kept, period budgets recalculated).
-- Dates and period count can change only before the first check-in.
create function public.update_cycle(p_id bigint, p_start date, p_end date, p_total numeric, p_mode text, p_n int)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := private.require_user();
  c public.cycles;
  has_checkins boolean;
  budgets numeric[];
begin
  perform private.validate_cycle(p_start, p_end, p_total, p_mode, p_n);
  select * into c from public.cycles where id = p_id and user_id = uid for update;
  if not found then raise exception 'cycle not found'; end if;

  select exists (select 1 from public.periods where cycle_id = p_id and status = 'completed') into has_checkins;
  if has_checkins and (p_start <> c.start_date or p_end <> c.end_date
      or p_n <> (select count(*) from public.periods where cycle_id = p_id)) then
    raise exception 'dates and number of periods can''t change after a check-in; undo the check-ins first';
  end if;

  update public.cycles set start_date = p_start, end_date = p_end, total_budget = p_total,
    division_mode = p_mode, num_periods = p_n where id = p_id;

  if has_checkins then
    budgets := private.calc_budgets(p_total, p_n, p_mode);
    update public.periods set budget = budgets[period_number] where cycle_id = p_id;
  else
    delete from public.periods where cycle_id = p_id;
    perform private.build_periods(p_id);
  end if;
  return private.cycle_json(p_id);
end $$;

create function public.check_in(p_period bigint, p_type text, p_amount numeric)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := private.require_user();
  p public.periods;
begin
  select per.* into p from public.periods per join public.cycles c on c.id = per.cycle_id
    where per.id = p_period and c.user_id = uid for update of per;
  if not found then raise exception 'period not found'; end if;
  if p.status = 'completed' then raise exception 'period already completed'; end if;
  if p_type not in ('sisa', 'defisit') then raise exception 'result_type must be ''sisa'' or ''defisit'''; end if;
  if p_amount is null or p_amount < 0 then raise exception 'result_amount must be non-negative'; end if;
  -- Dates have no time zone; a period has started for someone once UTC+14 reaches it.
  if p.start_date > ((now() at time zone 'utc') + interval '14 hours')::date then
    raise exception 'period has not started yet';
  end if;
  update public.periods set status = 'completed', result_type = p_type, result_amount = p_amount
    where id = p_period returning * into p;
  return to_jsonb(p);
end $$;

create function public.undo_check_in(p_period bigint)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := private.require_user();
  p public.periods;
begin
  update public.periods per set status = 'open', result_type = '', result_amount = 0
    from public.cycles c
    where per.id = p_period and c.id = per.cycle_id and c.user_id = uid
    returning per.* into p;
  if not found then raise exception 'period not found'; end if;
  return to_jsonb(p);
end $$;

-- Hands cycles migrated from the old backend to their owner: matches the old
-- Google account id against the Google identity Supabase verified at sign-in.
-- Idempotent; the app calls it after every sign-in.
create function public.claim_legacy_cycles()
returns int language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := private.require_user();
  n int;
begin
  update public.cycles set user_id = uid, legacy_user_id = null
    where user_id is null and legacy_user_id in (
      select i.provider_id from auth.identities i where i.user_id = uid and i.provider = 'google'
    );
  get diagnostics n = row_count;
  return n;
end $$;

create function public.waitlist_count()
returns bigint language sql stable security definer set search_path = '' as $$
  select count(*) from public.waitlist
$$;

revoke execute on all functions in schema public from public, anon;
grant execute on function public.create_cycle, public.update_cycle, public.check_in,
  public.undo_check_in, public.claim_legacy_cycles to authenticated;
grant execute on function public.waitlist_count to anon, authenticated;
